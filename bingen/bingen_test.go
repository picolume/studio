func readPropConfig(t *testing.T, data []byte, propID int) PropConfig {
	t.Helper()

	const headerSize = 16
	const configSize = 8

	offset := headerSize + (propID-1)*configSize
	if len(data) < offset+configSize {
		t.Fatalf("generated binary too short for prop %d config", propID)
	}

	return PropConfig{
		LedCount:      binary.LittleEndian.Uint16(data[offset : offset+2]),
		LedType:       data[offset+2],
		ColorOrder:    data[offset+3],
		BrightnessCap: data[offset+4],
		Reserved:      [3]uint8{data[offset+5], data[offset+6], data[offset+7]},
	}
}
