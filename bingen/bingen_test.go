func TestGenerateAppliesAssignedProfilesAndPatchOverrides(t *testing.T) {
	project := &Project{
		Settings: Settings{
			Profiles: []HardwareProfile{
				{ID: "base", AssignedIds: "1-2", LedCount: 60, LedType: 1, ColorOrder: 2, BrightnessCap: 120},
				{ID: "override", LedCount: 144, LedType: 4, ColorOrder: 5, BrightnessCap: 200},
			},
			Patch: map[string]string{"2": "override"},
		},
	}

	result, err := Generate(project)
	if err != nil {
		t.Fatalf("Generate returned error: %v", err)
	}

	prop1 := readPropConfig(t, result.Bytes, 1)
	if prop1.LedCount != 60 || prop1.LedType != 1 || prop1.ColorOrder != 2 || prop1.BrightnessCap != 120 {
		t.Fatalf("unexpected prop1 config: %+v", prop1)
	}

	prop2 := readPropConfig(t, result.Bytes, 2)
	if prop2.LedCount != 144 || prop2.LedType != 4 || prop2.ColorOrder != 5 || prop2.BrightnessCap != 200 {
		t.Fatalf("unexpected prop2 config after patch override: %+v", prop2)
	}

	prop3 := readPropConfig(t, result.Bytes, 3)
	if prop3.LedCount != 164 || prop3.BrightnessCap != 255 {
		t.Fatalf("expected default config for prop3, got %+v", prop3)
	}
}

